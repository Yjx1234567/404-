def api(path, data=None, cookie=None):
    req = urllib.request.Request(
        BASE + path,
        data=json.dumps(data).encode("utf-8") if data is not None else None,
        headers={"Content-Type": "application/json"},
        method="POST" if data is not None else "GET")
    if cookie:
        req.add_header("Cookie", cookie)
    with urllib.request.urlopen(req) as r:
        return r.status, r.read().decode("utf-8"), r.headers.get("Set-Cookie", "")


def main():
    status, body, setc = api("/login", ADMIN)
    if status != 200:
        print(f"[ERROR] 管理员登录失败（HTTP {status}）：{body}")
        raise SystemExit(1)
    cookie = setc.split(";")[0]

    ok = fail = 0
    for p in PROBLEMS:
        status, body, _ = api("/admin/problems", p, cookie)
        if status == 201:
            pid = json.loads(body).get("id", "?")
            print(f"  [OK] #{pid:<3} {p['title']}（{p['difficulty']}，"
                  f"{len(p['test_cases'])} 组用例）")
            ok += 1
        else:
            print(f"  [FAIL] {p['title']}（HTTP {status}）：{body}")
            fail += 1

    print(f"\n完成：成功 {ok} 题，失败 {fail} 题。")
    print("浏览器打开 http://localhost:8080 登录后即可在题库看到新题目。")


if __name__ == "__main__":
    main()
